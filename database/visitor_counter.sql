-- =====================================================================
-- Visitor Counter — นับผู้เข้าชมหน้า Home แบบ Unique Visitor (IP + วัน)
-- รันด้วย:  mysql -u runbkk_app -p runbkk < database/visitor_counter.sql
-- รันซ้ำได้: ไม่ลบตาราง/ข้อมูลเดิม
-- =====================================================================

SET NAMES utf8mb4;
SET time_zone = '+07:00';   -- ใช้เวลา Asia/Bangkok (UTC+7)

-- ---------------------------------------------------------------------
-- 1) สร้างตาราง (1 แถว = IP 1 ตัว ใน 1 วัน)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS visitors (
  ip_address     VARCHAR(45) NOT NULL,   -- IPv4 หรือ IPv6 (ยาวสุด 45 ตัวอักษร)
  visit_date     DATE        NOT NULL,   -- วันที่เข้าชม ตามเวลาไทย
  first_visit_at DATETIME    NOT NULL,   -- เวลาเข้าครั้งแรกของวัน (ไม่เปลี่ยน)
  last_visit_at  DATETIME    NOT NULL,   -- เวลาเข้าล่าสุด (อัปเดตทุกครั้งที่เข้า)
  PRIMARY KEY (ip_address, visit_date),  -- IP + วันที่ ซ้ำไม่ได้ = นับวันละ 1 ครั้ง
  KEY idx_visitors_date (visit_date)     -- ช่วยให้นับ "วันนี้" ได้เร็ว
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
-- 2) ข้อมูลตัวอย่าง (IP ช่วงสำหรับทำเอกสาร ไม่ใช่ IP คนจริง)
--    INSERT IGNORE = ถ้าแถวนี้มีอยู่แล้วให้ข้าม (รันไฟล์ซ้ำได้ไม่ error)
-- ---------------------------------------------------------------------
INSERT IGNORE INTO visitors (ip_address, visit_date, first_visit_at, last_visit_at) VALUES
  ('203.0.113.10', '2026-11-15', '2026-11-15 08:15:00', '2026-11-15 08:42:10'),  -- เข้าหลายครั้งในวันเดียว
  ('203.0.113.20', '2026-11-15', '2026-11-15 21:05:30', '2026-11-15 21:05:30'),  -- เข้าครั้งเดียว
  ('203.0.113.10', '2026-11-16', '2026-11-16 07:30:00', '2026-11-16 19:10:45'),  -- IP เดิม วันใหม่ = นับใหม่
  ('198.51.100.7', '2026-11-16', '2026-11-16 00:15:00', '2026-11-16 00:15:00'),  -- หลังเที่ยงคืนไทย = วันที่ 16
  ('2001:db8::1',  '2026-11-16', '2026-11-16 12:00:00', '2026-11-16 12:30:00');  -- ตัวอย่าง IPv6

-- ---------------------------------------------------------------------
-- 3) ตรวจผลลัพธ์
-- ---------------------------------------------------------------------
SELECT * FROM visitors ORDER BY visit_date, first_visit_at;

-- จำนวนผู้เข้าชมแยกรายวัน
SELECT visit_date, COUNT(*) AS unique_visitors
FROM visitors
GROUP BY visit_date
ORDER BY visit_date;
